#!/usr/bin/env pwsh
<#
.SYNOPSIS
Trigger thumbnail generation on the Phosyn server for videos listed in a no-thumb list file.

.DESCRIPTION
Reads a file generated by list-video-nothumb.ps1 (default: video-nothumb-list.txt),
extracts the JWT token, and triggers server-side rendition/thumbnail generation
via the reanalyze-metai endpoint (which re-generates video thumbnails using FFmpeg).
Can trigger all videos in bulk (default) or individually one by one.

.PARAMETER InputFile
Path to the list file containing video IDs and token (default: video-nothumb-list.txt).

.PARAMETER Batch
Switch to trigger reanalysis in a single bulk API call instead of one-by-one (default: true).

.PARAMETER Individual
Switch to trigger reanalysis for each video individually with progress output.

.PARAMETER ServerIp
Server IP address. If omitted, reads from .user file if available, or defaults to 127.0.0.1.

.EXAMPLE
.\generate-video-thumbs.ps1

Reads video-nothumb-list.txt and enqueues thumbnail generation on the server.

.EXAMPLE
.\generate-video-thumbs.ps1 -InputFile video-nothumb-list.txt -Individual
#>

param(
    [string]$InputFile = "video-nothumb-list.txt",
    [switch]$Individual,
    [string]$ServerIp
)

# Resolve server IP
if (-not $ServerIp) {
    $userFilePath = Split-Path -Parent $PSCommandPath | Join-Path -ChildPath ".user"
    if (Test-Path $userFilePath) {
        $lines = @(Get-Content $userFilePath)
        if ($lines.Count -gt 0 -and $lines[0].Trim()) {
            $ServerIp = $lines[0].Trim()
        }
    }
    if (-not $ServerIp) {
        $ServerIp = "127.0.0.1"
    }
}

$baseUrl = "http://$($ServerIp):8080/api/v1"

# Check input file
if (-not (Test-Path $InputFile)) {
    Write-Error "Input file not found: $InputFile"
    exit 1
}

Write-Host "Reading $InputFile..." -ForegroundColor Cyan
$content = Get-Content $InputFile -Raw

# Extract token from file (format: $token = 'eyJ0eXAi...')
$tokenMatch = [regex]::Match($content, "\`$token = '([^']+)'")
$token = if ($tokenMatch.Success) { $tokenMatch.Groups[1].Value } else { "" }

if (-not $token) {
    Write-Error "Could not extract authentication token from $InputFile"
    exit 1
}

# Parse video table lines
# Format: VIDEO | ID | FILENAME | SIZE
$lines = Get-Content $InputFile
$videos = @()

foreach ($line in $lines) {
    if ($line -match '^\s*$' -or $line -match '^====' -or $line -match '---' -or $line -match 'TYPE.*FILENAME.*SIZE' -or $line -match '\$token' -or $line -match 'Re-analyze' -or $line -match 'Download' -or $line -match 'Delete' -or $line -match 'Using these IDs') {
        continue
    }

    if ($line -match '\|' -and ($line -match 'VIDEO' -or $line -match 'IMAGE')) {
        $parts = $line -split '\|'
        if ($parts.Count -ge 4) {
            $videos += [PSCustomObject]@{
                Type     = $parts[0].Trim()
                Id       = $parts[1].Trim()
                Filename = $parts[2].Trim()
                Size     = $parts[3].Trim()
            }
        }
    }
}

if ($videos.Count -eq 0) {
    Write-Host "No video entries found to process in $InputFile." -ForegroundColor Yellow
    exit 0
}

Write-Host "Found $($videos.Count) video(s) to process." -ForegroundColor Green
Write-Host "Target server: $baseUrl" -ForegroundColor Cyan
Write-Host ""

$headers = @{
    "Authorization" = "Bearer $token"
    "Content-Type"  = "application/json"
}

if ($Individual) {
    Write-Host "Triggering thumbnail generation individually for each video..." -ForegroundColor Cyan
    $success = 0
    $failed = 0

    foreach ($video in $videos) {
        $endpoint = "$baseUrl/images/$($video.Id)/reanalyze-metai"
        try {
            Write-Host -NoNewline "  Queuing $($video.Filename) ($($video.Id))... "
            $res = Invoke-WebRequest -Uri $endpoint -Headers $headers -Method Post -ErrorAction Stop -UseBasicParsing
            Write-Host "QUEUED" -ForegroundColor Green
            $success++
        }
        catch {
            Write-Host "FAILED ($($_.Exception.Message))" -ForegroundColor Red
            $failed++
        }
    }

    Write-Host ""
    Write-Host "Completed: $success queued, $failed failed." -ForegroundColor Green
} else {
    Write-Host "Triggering bulk thumbnail generation via reanalyze-metai..." -ForegroundColor Cyan
    $ids = @($videos | ForEach-Object { $_.Id })
    $body = @{
        image_ids = $ids
    } | ConvertTo-Json

    try {
        $endpoint = "$baseUrl/images/reanalyze-metai"
        $res = Invoke-WebRequest -Uri $endpoint -Headers $headers -Method Post -Body $body -ErrorAction Stop -UseBasicParsing
        $data = $res.Content | ConvertFrom-Json
        Write-Host "Successfully queued $($data.queued) video(s) for thumbnail generation on the server." -ForegroundColor Green
    }
    catch {
        Write-Error "Failed to enqueue reanalysis: $($_.Exception.Message)"
        if ($_.ErrorDetails) {
            Write-Error "Server response: $($_.ErrorDetails.Message)"
        }
        exit 1
    }
}

Write-Host ""
Write-Host "The server's background worker processes thumbnails asynchronously." -ForegroundColor Gray
Write-Host "You can re-run '.\list-video-nothumb.ps1' to verify once processing finishes." -ForegroundColor Gray
