#!/usr/bin/env pwsh
<#
.SYNOPSIS
Delete duplicate files listed in duplicates-list.txt file.

.DESCRIPTION
Reads the duplicates-list.txt generated by find-duplicates.ps1 and automatically
deletes all the duplicate files listed in it. Performs soft delete (to trash) by default.
Generates a deletion report.

Automatically reads server IP from .user file and token from duplicates list file.

.PARAMETER InputFile
The duplicates list file (default: duplicates-list.txt)

.PARAMETER Purge
Switch to permanently delete instead of soft-delete to trash.
WARNING: Purged files cannot be restored!

.PARAMETER Force
Switch to skip confirmation prompt and delete immediately.

.PARAMETER Short
Switch to suppress detailed console output ("Files to delete:" and "Deleted:" lines).
Only shows summary and report location.

.EXAMPLE
.\delete-duplicates.ps1

Reads duplicates-list.txt, prompts for confirmation, then soft-deletes to trash.

.EXAMPLE
.\delete-duplicates.ps1 -InputFile my-duplicates.txt -Purge -Force

Permanently deletes all duplicates in my-duplicates.txt without confirmation.
#>

param(
    [string]$InputFile = "duplicates-list.txt",
    [switch]$Purge,
    [switch]$Force,
    [switch]$Short
)

try {
    # Read server IP from .user file
    $userFilePath = Split-Path -Parent $PSCommandPath | Join-Path -ChildPath ".user"
    if (-not (Test-Path $userFilePath)) {
        Write-Error "User credentials file not found at: $userFilePath"
        exit 1
    }
    
    $lines = @(Get-Content $userFilePath)
    $serverIp = $lines[0].Trim()
    if (-not (Test-Path $InputFile)) {
        Write-Error "Duplicates list file not found: $InputFile"
        exit 1
    }
    
    Write-Host "Reading $InputFile..." -ForegroundColor Cyan
    $content = Get-Content $InputFile -Raw
    $lines = Get-Content $InputFile
    
    $tokenMatch = [regex]::Match($content, "\`$token = '([^']+)'")
    $token = if ($tokenMatch.Success) { $tokenMatch.Groups[1].Value } else { "" }
    
    if (-not $token) {
        Write-Error "Could not extract token from input file"
        exit 1
    }
    
    $duplicates = @()
    
    foreach ($line in $lines) {
        if ($line -match '^\s*$' -or $line -match '^====' -or $line -match '---' -or $line -match 'TYPE.*FILENAME.*SIZE' -or $line -match 'Token:' -or $line -match '\$token' -or $line -match 'Files to Delete' -or $line -match 'Usage:' -or $line -match 'Generated:') {
            continue
        }
        
        if ($line -match '\|' -and ($line -match 'IMAGE' -or $line -match 'VIDEO')) {
            $parts = $line -split '\|'
            if ($parts.Count -eq 4) {
                $obj = New-Object PSObject
                $obj | Add-Member -Type NoteProperty -Name Type -Value $parts[0].Trim()
                $obj | Add-Member -Type NoteProperty -Name ID -Value $parts[1].Trim()
                $obj | Add-Member -Type NoteProperty -Name Filename -Value $parts[2].Trim()
                $obj | Add-Member -Type NoteProperty -Name Size -Value $parts[3].Trim()
                $duplicates += $obj
            }
        }
    }
    
    if ($duplicates.Count -eq 0) {
        Write-Error "No duplicate files found in $InputFile"
        exit 1
    }
    
    Write-Host "Found $($duplicates.Count) duplicate files to delete" -ForegroundColor Yellow
    Write-Host ""
    
    if (-not $Short) {
        Write-Host "Files to delete:" -ForegroundColor Yellow
        foreach ($dup in $duplicates) {
            Write-Host "  - $($dup.Filename) ($($dup.Size))" -ForegroundColor Gray
        }
        Write-Host ""
    }
    
    if (-not $Force) {
        $deleteType = if ($Purge) { "permanently deleted" } else { "moved to trash" }
        Write-Host "These files will be $deleteType (cannot be undone if purged)" -ForegroundColor Yellow
        Write-Host ""
        
        $confirm = Read-Host "Continue? (Y/N)"
        if ($confirm -ne "Y" -and $confirm -ne "y") {
            Write-Host "Cancelled" -ForegroundColor Gray
            exit 0
        }
    }
    
    Write-Host ""
    $baseUrl = "http://$($ServerIp):8080/api/v1"
    $deletedCount = 0
    $failedCount = 0
    $deletedList = @()
    $failedList = @()
    
    foreach ($dup in $duplicates) {
        $id = $dup.ID
        $filename = $dup.Filename
        
        try {
            if ($Purge) {
                $url = "$baseUrl/images/$id/purge"
            } else {
                $url = "$baseUrl/images/$id"
            }
            
            Invoke-WebRequest -Uri $url -Headers @{ "Authorization" = "Bearer $token" } -Method Delete -ErrorAction Stop -UseBasicParsing | Out-Null
            
            $deletedCount++
            $deletedList += $dup
            if (-not $Short) {
                Write-Host "Deleted: $filename" -ForegroundColor Green
            }
        }
        catch {
            $failedCount++
            $errObj = New-Object PSObject
            $errObj | Add-Member -Type NoteProperty -Name ID -Value $id
            $errObj | Add-Member -Type NoteProperty -Name Filename -Value $filename
            $errObj | Add-Member -Type NoteProperty -Name Error -Value $_.Exception.Message
            $failedList += $errObj
            Write-Host "Failed: $filename - $($_.Exception.Message)" -ForegroundColor Red
        }
    }
    
    Write-Host ""
    Write-Host "Deletion Report" -ForegroundColor Cyan
    
    $reportFile = "deletion-report-$(Get-Date -Format 'yyyyMMdd-HHmmss').txt"
    
    $reportLines = @()
    $reportLines += "Deletion Report"
    $timestamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
    $reportLines += "Generated: $timestamp"
    $reportLines += ""
    $reportLines += "Summary:"
    $reportLines += "  Total requested: $($duplicates.Count)"
    $reportLines += "  Successfully deleted: $deletedCount"
    $reportLines += "  Failed: $failedCount"
    $delType = if ($Purge) { 'Permanent' } else { 'Soft delete to trash' }
    $reportLines += "  Deletion type: $delType"
    $reportLines += ""
    
    if ($deletedCount -gt 0) {
        $reportLines += "Successfully Deleted Files:"
        $reportLines += "======================================================================"
        $reportLines += "TYPE    | ID                                   | FILENAME             | SIZE"
        $reportLines += "----------------------------------------------------------------------"
        foreach ($item in $deletedList) {
            $line = $item.Type + " | " + $item.ID + " | " + $item.Filename + " | " + $item.Size
            $reportLines += $line
        }
        $reportLines += "======================================================================"
        $reportLines += ""
    }
    
    if ($failedCount -gt 0) {
        $reportLines += "Failed Deletions:"
        $reportLines += "======================================================================"
        foreach ($item in $failedList) {
            $reportLines += $item.Filename + " (ID: " + $item.ID + ")"
            $reportLines += "  Error: " + $item.Error
        }
        $reportLines += "======================================================================"
        $reportLines += ""
    }
    
    $reportLines | Out-File -FilePath $reportFile -Encoding UTF8
    
    Write-Host "Deleted: $deletedCount files" -ForegroundColor Green
    $failColor = if ($failedCount -eq 0) { 'Green' } else { 'Yellow' }
    Write-Host "Failed:  $failedCount files" -ForegroundColor $failColor
    Write-Host ""
    Write-Host "Report saved to: $(Resolve-Path $reportFile)" -ForegroundColor Cyan
}
catch {
    Write-Error "Error processing deletions: $($_.Exception.Message)"
    exit 1
}
